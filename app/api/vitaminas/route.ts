import { NextResponse } from 'next/server';
import type { ResultSetHeader, RowDataPacket } from 'mysql2';
import { pgPool, pool } from '@/lib/db';

export const dynamic = 'force-dynamic';

let tablaLista: Promise<void> | undefined;

function asegurarTablaRecetas() {
  if (!tablaLista) {
    tablaLista = pgPool.query(`
      CREATE TABLE IF NOT EXISTS recetas (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        dni_paciente CHAR(8) NOT NULL,
        nombre_paciente VARCHAR(200) NOT NULL,
        "vitaminaNombre" VARCHAR(200) NOT NULL,
        dosis VARCHAR(100),
        via VARCHAR(100),
        observaciones TEXT,
        activo BOOLEAN NOT NULL DEFAULT TRUE,
        "fechaAplicacion" TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )
    `).then(() => undefined).catch(error => {
      tablaLista = undefined;
      throw error;
    });
  }
  return tablaLista;
}

export async function GET() {
  try {
    await asegurarTablaRecetas();
    const [rows] = await pool.query<RowDataPacket[]>('SELECT * FROM recetas ORDER BY id DESC');
    return NextResponse.json(rows);
  } catch (error) {
    console.error('Error al listar vitaminas:', error);
    return NextResponse.json({ error: 'No se pudieron cargar los tratamientos.' }, { status: 503 });
  }
}

export async function POST(request: Request) {
  let body: Record<string, unknown>;
  try {
    body = await request.json();
  } catch {
    return NextResponse.json({ error: 'Solicitud inválida' }, { status: 400 });
  }
  const dni = String(body.dni_paciente ?? '').trim();
  const nombre = String(body.nombre_paciente ?? '').trim();
  const vitamina = String(body.vitaminaNombre ?? '').trim();
  const dosis = String(body.dosis ?? '').trim();
  if (!/^\d{8}$/.test(dni) || !nombre || !vitamina || !dosis) {
    return NextResponse.json({ error: 'Complete el paciente, la vitamina o suero y la dosis.' }, { status: 400 });
  }
  try {
    await asegurarTablaRecetas();
    const [result] = await pool.execute<ResultSetHeader>(
      'INSERT INTO recetas (dni_paciente, nombre_paciente, "vitaminaNombre", dosis, via, observaciones) VALUES (?, ?, ?, ?, ?, ?)',
      [dni, nombre, vitamina, dosis, String(body.via ?? '').trim(), String(body.observaciones ?? '').trim()]
    );
    return NextResponse.json({ success: true, id: result.insertId }, { status: 201 });
  } catch (error) {
    console.error('Error al guardar vitamina:', error);
    const codigo = error && typeof error === 'object' && 'code' in error && typeof error.code === 'string'
      ? error.code
      : null;
    return NextResponse.json({
      error: codigo ? `No se pudo guardar el tratamiento. Código: ${codigo}` : 'No se pudo guardar el tratamiento.'
    }, { status: 503 });
  }
}

export async function PATCH(request: Request) {
  const dni = new URL(request.url).searchParams.get('dni');
  if (!dni) return NextResponse.json({ error: 'DNI requerido' }, { status: 400 });
  try {
    await asegurarTablaRecetas();
    await pool.execute<ResultSetHeader>('UPDATE recetas SET activo = FALSE WHERE dni_paciente = ?', [dni]);
    return NextResponse.json({ success: true });
  } catch (error) {
    console.error('Error al desmarcar tratamiento:', error);
    return NextResponse.json({ error: 'No se pudo actualizar el tratamiento.' }, { status: 503 });
  }
}
