import { NextResponse } from 'next/server';
import type { ResultSetHeader, RowDataPacket } from 'mysql2';
import { pgPool, pool } from '@/lib/db';

export const dynamic = 'force-dynamic';

type ColumnasRecetas = { vitamina: string; fecha: string };
let tablaLista: Promise<ColumnasRecetas> | undefined;

const citarColumna = (nombre: string) => `"${nombre.replaceAll('"', '""')}"`;

function asegurarTablaRecetas() {
  if (!tablaLista) {
    tablaLista = (async () => {
      await pgPool.query(`
        CREATE TABLE IF NOT EXISTS recetas (
          id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
          dni_paciente CHAR(8) NOT NULL,
          nombre_paciente VARCHAR(200) NOT NULL,
          "vitaminaNombre" VARCHAR(200) NOT NULL,
          dosis VARCHAR(100),
          via VARCHAR(100),
          observaciones TEXT,
          activo BOOLEAN NOT NULL DEFAULT TRUE,
          "fechaAplicacion" TIMESTAMPTZ NOT NULL DEFAULT NOW()
        )
      `);
      await pgPool.query(`
        ALTER TABLE recetas
          ADD COLUMN IF NOT EXISTS dosis VARCHAR(100),
          ADD COLUMN IF NOT EXISTS via VARCHAR(100),
          ADD COLUMN IF NOT EXISTS observaciones TEXT,
          ADD COLUMN IF NOT EXISTS activo BOOLEAN NOT NULL DEFAULT TRUE
      `);
      const { rows } = await pgPool.query<{ column_name: string }>(`
        SELECT column_name FROM information_schema.columns
        WHERE table_schema = current_schema() AND table_name = 'recetas'
      `);
      const nombres = new Set(rows.map((row: { column_name: string }) => row.column_name));
      let nombreVitamina = ['vitaminaNombre', 'vitaminanombre', 'vitamina_nombre', 'nombre_vitamina', 'medicamento']
        .find(nombre => nombres.has(nombre));
      if (!nombreVitamina) {
        await pgPool.query('ALTER TABLE recetas ADD COLUMN IF NOT EXISTS "vitaminaNombre" VARCHAR(200)');
        nombreVitamina = 'vitaminaNombre';
      }
      let nombreFecha = ['fechaAplicacion', 'fechaaplicacion', 'fecha_aplicacion'].find(nombre => nombres.has(nombre));
      if (!nombreFecha) {
        await pgPool.query('ALTER TABLE recetas ADD COLUMN IF NOT EXISTS "fechaAplicacion" TIMESTAMPTZ');
        await pgPool.query('ALTER TABLE recetas ALTER COLUMN "fechaAplicacion" SET DEFAULT NOW()');
        nombreFecha = 'fechaAplicacion';
      }
      return {
        vitamina: citarColumna(nombreVitamina),
        fecha: citarColumna(nombreFecha)
      };
    })().catch(error => {
      tablaLista = undefined;
      throw error;
    });
  }
  return tablaLista;
}

export async function GET() {
  try {
    const columnas = await asegurarTablaRecetas();
    const [rows] = await pool.query<RowDataPacket[]>(
      `SELECT *, ${columnas.vitamina} AS "vitaminaNombre", ${columnas.fecha} AS "fechaAplicacion" FROM recetas ORDER BY id DESC`
    );
    return NextResponse.json(rows);
  } catch (error) {
    console.error('Error al listar vitaminas:', error);
    return NextResponse.json({ error: 'No se pudieron cargar los tratamientos.' }, { status: 503 });
  }
}

export async function POST(request: Request) {
  let body: Record<string, unknown>;
  try {
    body = await request.json();
  } catch {
    return NextResponse.json({ error: 'Solicitud inválida' }, { status: 400 });
  }
  const dni = String(body.dni_paciente ?? '').trim();
  const nombre = String(body.nombre_paciente ?? '').trim();
  const entradas = body.tratamientos === undefined ? [body] : body.tratamientos;
  if (!/^\d{8}$/.test(dni) || !nombre || !Array.isArray(entradas) || entradas.length < 1 || entradas.length > 50) {
    return NextResponse.json({ error: 'Indique un paciente y entre 1 y 50 vitaminas o sueros.' }, { status: 400 });
  }
  const aplicaciones = entradas.map(entrada => {
    const item = entrada && typeof entrada === 'object' && !Array.isArray(entrada) ? entrada as Record<string, unknown> : {};
    return {
      vitaminaNombre: String(item.vitaminaNombre ?? '').trim(),
      dosis: String(item.dosis ?? '').trim(),
      via: String(item.via ?? '').trim(),
      observaciones: String(item.observaciones ?? '').trim()
    };
  });
  if (aplicaciones.some(item => !item.vitaminaNombre || !item.dosis || !item.via ||
    item.vitaminaNombre.length > 200 || item.dosis.length > 100 || item.via.length > 100)) {
    return NextResponse.json({ error: 'Complete nombre, dosis y vía de cada vitamina o suero y revise la longitud de los datos.' }, { status: 400 });
  }
  try {
    const columnas = await asegurarTablaRecetas();
    const cliente = await pgPool.connect();
    try {
      const fechaComun = new Date();
      const guardados = [];
      await cliente.query('BEGIN');
      for (const item of aplicaciones) {
        const { rows } = await cliente.query<{ id: string | number; fechaAplicacion: Date }>(
          `INSERT INTO recetas (dni_paciente, nombre_paciente, ${columnas.vitamina}, dosis, via, observaciones, ${columnas.fecha})
           VALUES ($1, $2, $3, $4, $5, $6, $7)
           RETURNING id, ${columnas.fecha} AS "fechaAplicacion"`,
          [dni, nombre, item.vitaminaNombre, item.dosis, item.via, item.observaciones, fechaComun]
        );
        guardados.push({
          id: Number(rows[0].id),
          dni_paciente: dni,
          ...item,
          fechaAplicacion: rows[0].fechaAplicacion,
          activo: true
        });
      }
      await cliente.query('COMMIT');
      return NextResponse.json({ success: true, data: guardados, id: guardados[0].id, fechaAplicacion: guardados[0].fechaAplicacion }, { status: 201 });
    } catch (error) {
      await cliente.query('ROLLBACK');
      throw error;
    } finally {
      cliente.release();
    }
  } catch (error) {
    console.error('Error al guardar vitamina:', error);
    const codigo = error && typeof error === 'object' && 'code' in error && typeof error.code === 'string'
      ? error.code
      : null;
    return NextResponse.json({
      error: codigo ? `No se pudo guardar el tratamiento. Código: ${codigo}` : 'No se pudo guardar el tratamiento.'
    }, { status: 503 });
  }
}

export async function PUT(request: Request) {
  let body: Record<string, unknown>;
  try {
    body = await request.json();
  } catch {
    return NextResponse.json({ error: 'Solicitud inválida' }, { status: 400 });
  }
  const id = Number(body.id);
  const dni = String(body.dni_paciente ?? '').trim();
  const vitamina = String(body.vitaminaNombre ?? '').trim();
  const dosis = String(body.dosis ?? '').trim();
  if (!Number.isSafeInteger(id) || id <= 0 || !/^\d{8}$/.test(dni) || !vitamina || !dosis) {
    return NextResponse.json({ error: 'Complete el paciente, la vitamina o suero y la dosis.' }, { status: 400 });
  }
  try {
    const columnas = await asegurarTablaRecetas();
    const [result] = await pool.execute<ResultSetHeader>(
      `UPDATE recetas SET ${columnas.vitamina} = ?, dosis = ?, via = ?, observaciones = ? WHERE id = ? AND dni_paciente = ?`,
      [vitamina, dosis, String(body.via ?? '').trim(), String(body.observaciones ?? '').trim(), id, dni]
    );
    if (!result.affectedRows) return NextResponse.json({ error: 'Tratamiento no encontrado.' }, { status: 404 });
    return NextResponse.json({ success: true });
  } catch (error) {
    console.error('Error al editar vitamina:', error);
    return NextResponse.json({ error: 'No se pudo actualizar el tratamiento.' }, { status: 503 });
  }
}

export async function DELETE(request: Request) {
  const { searchParams } = new URL(request.url);
  const id = Number(searchParams.get('id'));
  const dni = searchParams.get('dni')?.trim() || '';
  if (!Number.isSafeInteger(id) || id <= 0 || !/^\d{8}$/.test(dni)) {
    return NextResponse.json({ error: 'Tratamiento o paciente inválido.' }, { status: 400 });
  }
  try {
    await asegurarTablaRecetas();
    const [result] = await pool.execute<ResultSetHeader>(
      'DELETE FROM recetas WHERE id = ? AND dni_paciente = ?', [id, dni]
    );
    if (!result.affectedRows) return NextResponse.json({ error: 'Tratamiento no encontrado.' }, { status: 404 });
    return NextResponse.json({ success: true });
  } catch (error) {
    console.error('Error al eliminar vitamina:', error);
    return NextResponse.json({ error: 'No se pudo eliminar el tratamiento.' }, { status: 503 });
  }
}

export async function PATCH(request: Request) {
  const dni = new URL(request.url).searchParams.get('dni');
  if (!dni) return NextResponse.json({ error: 'DNI requerido' }, { status: 400 });
  try {
    await asegurarTablaRecetas();
    await pool.execute<ResultSetHeader>('UPDATE recetas SET activo = FALSE WHERE dni_paciente = ?', [dni]);
    return NextResponse.json({ success: true });
  } catch (error) {
    console.error('Error al desmarcar tratamiento:', error);
    return NextResponse.json({ error: 'No se pudo actualizar el tratamiento.' }, { status: 503 });
  }
}
