-- Este esquema es para una base nueva. No contiene datos de pacientes.

CREATE TABLE IF NOT EXISTS pacientes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dni CHAR(8) NOT NULL UNIQUE,
  nombre VARCHAR(200) NOT NULL,
  telefono VARCHAR(30),
  edad SMALLINT,
  genero VARCHAR(30),
  direccion VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS triaje (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dni_paciente CHAR(8) NOT NULL,
  nombre_paciente VARCHAR(200) NOT NULL,
  edad SMALLINT,
  talla NUMERIC(6,2),
  peso NUMERIC(6,2),
  imc NUMERIC(6,2),
  pulso VARCHAR(30),
  so2 VARCHAR(30),
  temperatura VARCHAR(30),
  hb VARCHAR(30),
  presion VARCHAR(30),
  observaciones TEXT,
  fecha TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS triaje_dni_paciente_idx ON triaje (dni_paciente);

CREATE TABLE IF NOT EXISTS triaje_adjuntos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  triaje_id BIGINT NOT NULL REFERENCES triaje(id) ON DELETE CASCADE,
  nombre VARCHAR(255) NOT NULL,
  tipo VARCHAR(100) NOT NULL,
  contenido BYTEA NOT NULL,
  fecha TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS triaje_adjuntos_triaje_id_idx ON triaje_adjuntos (triaje_id);

CREATE TABLE IF NOT EXISTS pagos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paciente_id BIGINT,
  registrado_por BIGINT,
  dni_paciente CHAR(8) NOT NULL,
  nombre_paciente VARCHAR(200) NOT NULL,
  concepto VARCHAR(255) NOT NULL,
  monto NUMERIC(12,2) NOT NULL,
  tipo_ingreso VARCHAR(60) NOT NULL,
  destinatario_pago VARCHAR(20) NOT NULL,
  metodo_pago VARCHAR(60) NOT NULL,
  fecha TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS pagos_dni_paciente_idx ON pagos (dni_paciente);

CREATE TABLE IF NOT EXISTS consultas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dni_paciente CHAR(8) NOT NULL,
  fecha VARCHAR(40) NOT NULL,
  motivo TEXT,
  diagnostico TEXT,
  receta TEXT,
  dieta TEXT,
  imagen_url TEXT
);
CREATE INDEX IF NOT EXISTS consultas_dni_paciente_idx ON consultas (dni_paciente);

CREATE TABLE IF NOT EXISTS consulta_adjuntos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  consulta_id BIGINT NOT NULL REFERENCES consultas(id) ON DELETE CASCADE,
  nombre VARCHAR(255) NOT NULL,
  tipo VARCHAR(100) NOT NULL,
  contenido BYTEA NOT NULL,
  fecha TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS consulta_adjuntos_consulta_id_idx ON consulta_adjuntos (consulta_id);

CREATE TABLE IF NOT EXISTS citas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  paciente_id BIGINT,
  doctor_id BIGINT,
  dni_paciente CHAR(8) NOT NULL,
  nombre_paciente VARCHAR(200) NOT NULL,
  telefono VARCHAR(30),
  fecha DATE NOT NULL,
  hora TIME NOT NULL,
  fecha_hora_cita TIMESTAMP NOT NULL,
  motivo TEXT,
  estado VARCHAR(20) NOT NULL DEFAULT 'programada'
);
CREATE INDEX IF NOT EXISTS citas_dni_paciente_idx ON citas (dni_paciente);
CREATE INDEX IF NOT EXISTS citas_fecha_idx ON citas (fecha);

CREATE TABLE IF NOT EXISTS internamientos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dni_paciente CHAR(8) NOT NULL,
  nombre_paciente VARCHAR(200) NOT NULL,
  cama VARCHAR(50) NOT NULL,
  fecha_ingreso DATE NOT NULL,
  tiempo_estancia_num SMALLINT,
  tiempo_estancia_unidad VARCHAR(20),
  fecha_estimada_salida DATE,
  diagnostico TEXT,
  observaciones TEXT,
  estado VARCHAR(20) NOT NULL DEFAULT 'hospitalizado',
  fecha_salida DATE,
  hora_salida TIME,
  motivo_salida TEXT,
  notas_salida TEXT
);
CREATE INDEX IF NOT EXISTS internamientos_dni_paciente_idx ON internamientos (dni_paciente);

CREATE TABLE IF NOT EXISTS recetas (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dni_paciente CHAR(8) NOT NULL,
  nombre_paciente VARCHAR(200) NOT NULL,
  "vitaminaNombre" VARCHAR(200) NOT NULL,
  dosis VARCHAR(100),
  via VARCHAR(100),
  observaciones TEXT,
  activo BOOLEAN NOT NULL DEFAULT TRUE,
  "fechaAplicacion" TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS recetas_dni_paciente_idx ON recetas (dni_paciente);

