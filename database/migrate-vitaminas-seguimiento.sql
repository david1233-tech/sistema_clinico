CREATE TABLE IF NOT EXISTS vitaminas_controles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dni_paciente CHAR(8) NOT NULL,
  fecha DATE NOT NULL,
  presion VARCHAR(30), pulso VARCHAR(30), saturacion VARCHAR(30), frecuencia_respiratoria VARCHAR(30),
  temperatura VARCHAR(30), peso VARCHAR(30), imc VARCHAR(30), grasa_corporal VARCHAR(30), grasa_visceral VARCHAR(30),
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT vitaminas_controles_paciente_fecha_unique UNIQUE (dni_paciente, fecha)
);
CREATE INDEX IF NOT EXISTS vitaminas_controles_dni_idx ON vitaminas_controles (dni_paciente);

CREATE TABLE IF NOT EXISTS vitaminas_procedimientos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  dni_paciente CHAR(8) NOT NULL,
  categoria VARCHAR(80) NOT NULL,
  fecha DATE NOT NULL,
  descripcion TEXT NOT NULL,
  clave_solicitud UUID NOT NULL UNIQUE,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS vitaminas_procedimientos_dni_idx ON vitaminas_procedimientos (dni_paciente);
