import { pgPool } from '@/lib/db';

let initialized: Promise<void> | undefined;

export function ensureConsultaAdjuntos() {
  if (!initialized) {
    initialized = (async () => {
      await pgPool.query(`CREATE TABLE IF NOT EXISTS consulta_adjuntos (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        consulta_id BIGINT NOT NULL REFERENCES consultas(id) ON DELETE CASCADE,
        nombre VARCHAR(255) NOT NULL,
        tipo VARCHAR(100) NOT NULL,
        contenido BYTEA NOT NULL,
        fecha TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )`);
      await pgPool.query('CREATE INDEX IF NOT EXISTS consulta_adjuntos_consulta_id_idx ON consulta_adjuntos (consulta_id)');
    })().catch(error => {
      initialized = undefined;
      throw error;
    });
  }
  return initialized;
}

