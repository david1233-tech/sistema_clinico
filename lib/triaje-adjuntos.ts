import { pgPool } from '@/lib/db';

let initialized: Promise<void> | undefined;

export function ensureTriajeAdjuntos() {
  if (!initialized) {
    initialized = (async () => {
      await pgPool.query(`CREATE TABLE IF NOT EXISTS triaje_adjuntos (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        triaje_id BIGINT NOT NULL REFERENCES triaje(id) ON DELETE CASCADE,
        nombre VARCHAR(255) NOT NULL,
        tipo VARCHAR(100) NOT NULL,
        contenido BYTEA NOT NULL,
        fecha TIMESTAMPTZ NOT NULL DEFAULT NOW()
      )`);
      await pgPool.query('CREATE INDEX IF NOT EXISTS triaje_adjuntos_triaje_id_idx ON triaje_adjuntos (triaje_id)');
    })().catch(error => {
      initialized = undefined;
      throw error;
    });
  }
  return initialized;
}

