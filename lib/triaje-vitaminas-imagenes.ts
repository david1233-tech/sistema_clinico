import { pgPool } from '@/lib/db';

let initialized: Promise<void> | undefined;

export function ensureTriajeVitaminasImagenes() {
  if (!initialized) initialized = (async () => {
    await pgPool.query(`CREATE TABLE IF NOT EXISTS triaje_vitaminas_imagenes (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      dni_paciente CHAR(8) NOT NULL,
      nombre VARCHAR(255) NOT NULL,
      tipo VARCHAR(100) NOT NULL,
      contenido BYTEA NOT NULL,
      fecha_subida TIMESTAMPTZ NOT NULL DEFAULT NOW(),
      fecha_aplicacion TIMESTAMPTZ NOT NULL
    )`);
    await pgPool.query('CREATE INDEX IF NOT EXISTS triaje_vitaminas_imagenes_dni_idx ON triaje_vitaminas_imagenes (dni_paciente)');
  })().catch(error => { initialized = undefined; throw error; });
  return initialized;
}

