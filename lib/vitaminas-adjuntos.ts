import { pgPool } from '@/lib/db';

let initialized: Promise<void> | undefined;

export function ensureVitaminasAdjuntos() {
  if (!initialized) initialized = (async () => {
    await pgPool.query(`CREATE TABLE IF NOT EXISTS vitaminas_adjuntos (
      id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      receta_id BIGINT NOT NULL REFERENCES recetas(id) ON DELETE CASCADE,
      nombre VARCHAR(255) NOT NULL,
      tipo VARCHAR(100) NOT NULL,
      contenido BYTEA NOT NULL,
      fecha TIMESTAMPTZ NOT NULL DEFAULT NOW()
    )`);
    await pgPool.query('CREATE INDEX IF NOT EXISTS vitaminas_adjuntos_receta_idx ON vitaminas_adjuntos (receta_id)');
  })().catch(error => { initialized = undefined; throw error; });
  return initialized;
}
